const assert = require("node:assert/strict");
const { execFileSync } = require("node:child_process");
const { createHash } = require("node:crypto");
const { mkdtempSync, readFileSync, rmSync } = require("node:fs");
const os = require("node:os");
const path = require("node:path");
const { after, before, test } = require("node:test");
const { checkProvenance, applyProvenanceGate } = require("./generated-provenance.cjs");

const headSHA = "a".repeat(40);
const parentSHA = "b".repeat(40);
const header = "// Copyright (c) Microsoft Corporation.\n// Code generated by Microsoft (R) Go Code Generator. DO NOT EDIT.\n";
const source = `${header}package generated\n\nconst Value = "a b"\n`;
let temporary;
let tokensPath;

before(() => {
  temporary = mkdtempSync(path.join(os.tmpdir(), "generated-provenance-"));
  tokensPath = path.join(temporary, process.platform === "win32" ? "gotokens.exe" : "gotokens");
  execFileSync("go", ["build", "-o", tokensPath, path.join(__dirname, "gotokens.go")], {
    stdio: "pipe",
    timeout: 120000,
  });
});
after(() => {
  if (temporary) rmSync(temporary, { recursive: true });
});

function fixture(changes = [{ filename: "generated.go", before: source, after: source.replace('"a b"', '"ab"') }]) {
  const state = {
    pr: { number: 42, state: "open", head: { sha: headSHA }, base: { sha: parentSHA }, changed_files: changes.length, commits: 1 },
    commits: [{ sha: headSHA, author: { login: "developer" }, commit: { author: { name: "azure-sdk" } } }],
    files: [],
    blobs: new Map(),
    previous: new Map(),
    errors: [],
    pages: [],
  };
  function addBlob(value) {
    const data = Buffer.isBuffer(value) ? value : Buffer.from(value);
    const sha = createHash("sha1").update(`blob ${data.length}\0`).update(data).digest("hex");
    state.blobs.set(sha, { sha, size: data.length, encoding: "base64", content: data.toString("base64") });
    return sha;
  }
  for (const change of changes) {
    const status = change.status || "modified";
    const file = {
      filename: change.filename,
      status,
      additions: 1,
      deletions: 1,
      sha: change.after === null ? addBlob(change.before) : addBlob(change.after),
    };
    if (change.previous_filename) file.previous_filename = change.previous_filename;
    if (change.before !== null) state.previous.set(`${parentSHA}:${change.previous_filename || change.filename}`, addBlob(change.before));
    state.files.push(file);
  }
  state.changedFiles = structuredClone(state.files);
  state.detail = {
    sha: headSHA,
    parents: [{ sha: parentSHA }],
    stats: { additions: state.files.length, deletions: state.files.length },
  };
  state.github = {
    rest: {
      pulls: {
        get: async () => ({ data: structuredClone(state.pr) }),
        listFiles: async () => ({ data: state.changedFiles }),
        listCommits: async () => ({ data: state.commits }),
      },
      repos: {
        getCommit: async ({ ref, page, per_page }) => {
          assert.equal(ref, headSHA);
          assert.equal(per_page, 100);
          state.pages.push(page);
          return { data: { ...state.detail, files: state.files.slice((page - 1) * 100, page * 100) } };
        },
        getContent: async ({ path, ref }) => {
          const sha = state.previous.get(`${ref}:${path}`);
          if (!sha) throw new Error(`Missing parent file ${path}.`);
          return { data: { type: "file", sha } };
        },
      },
      git: {
        getBlob: async ({ file_sha }) => {
          const data = state.blobs.get(file_sha);
          if (!data) throw new Error("Blob API unavailable.");
          return { data };
        },
      },
    },
    paginate: async (method, options) => {
      assert.equal(options.per_page, 100);
      return (await method(options)).data;
    },
  };
  state.run = () => checkProvenance({
    github: state.github,
    context: { repo: { owner: "Azure", repo: "azure-sdk-for-go" } },
    core: { info: () => {}, error: (message) => state.errors.push(message) },
  }, { prNumber: 42, headSHA, tokensPath });
  return state;
}

