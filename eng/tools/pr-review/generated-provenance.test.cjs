test("the configured protection marker replaces the default and is literal text", async () => {
  const state = fixture([
    { filename: "custom.go", before: "[READ-ONLY]\nold", after: "[READ-ONLY]\nnew" },
    { filename: "default.go", before: source, after: `${source}\n` },
  ]);
  const custom = await state.run({ protectedFileMarker: "[READ-ONLY]" });
  assert.deepEqual(custom.findings.map((finding) => finding.file), ["custom.go"]);
  const defaults = await state.run();
  assert.deepEqual(defaults.findings.map((finding) => finding.file), ["default.go"]);
});

