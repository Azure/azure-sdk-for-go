for (const [name, mutate] of [
  ["incomplete PR files", (state) => state.pr.changed_files++],
  ["incomplete PR commits", (state) => state.pr.commits++],
  ["unexpected PR head", (state) => state.pr.head.sha = parentSHA],
  ["merge commits", (state) => state.detail.parents.push({ sha: "c".repeat(40) })],
  ["missing parent blobs", (state) => state.previous.clear()],
  ["missing blobs", (state) => state.blobs.clear()],
  ["truncated blobs", (state) => state.blobs.values().next().value.content = ""],
  ["GitHub's commit file limit", (state) => {
    state.files = Array.from({ length: 3000 }, (_, i) => ({ ...state.files[0], filename: `file${i}.go` }));
  }],
  ["malformed generated Go", (state) => {
    const file = state.files[0];
    const value = state.blobs.get(file.sha);
    const content = Buffer.from(`${header}package`);
    const sha = createHash("sha1").update(`blob ${content.length}\0`).update(content).digest("hex");
    state.blobs.set(sha, { ...value, sha, content: content.toString("base64"), size: content.length });
    file.sha = sha;
  }],
]) {
  test(`${name} fails closed with an explicit verification error`, async () => {
    const state = fixture();
    mutate(state);
    const result = await state.run();
    assert.equal(result.status, "unverifiable");
    assert.equal(result.errors.length, 1);
    assert.equal(state.errors.length, 1);
  });
}

test("a PR changed during verification cannot receive a pass", async () => {
  const state = fixture([{ filename: "handwritten.go", before: "package p\n", after: "package p\n" }]);
  let calls = 0;
  state.github.rest.pulls.get = async () => {
    const pr = structuredClone(state.pr);
    if (++calls > 1) pr.base.sha = "c".repeat(40);
    return { data: pr };
  };
  assert.equal((await state.run()).status, "unverifiable");
});

